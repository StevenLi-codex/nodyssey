"""Export existing Compose copy into native Apple localization, without changing its source."""
from pathlib import Path
import argparse
import re
import xml.etree.ElementTree as ET

TOKEN = re.compile(r'%%|%(?:\d+\$)?[-+#0]*(?:\d+)?(?:\.\d+)?[A-Za-z@]')
ESCAPES = {'n': '\n', 'r': '\r', 't': '\t', '\\': '\\', "'": "'", '"': '"'}


def apple_format(text):
    def convert(match):
        token = match.group()
        if token == '%%':
            return token
        if token[-1] == 's':
            return token[:-1] + '@'
        if token[-1] in 'df@':
            return token
        raise ValueError('Unsupported format token: ' + token)
    return TOKEN.sub(convert, text)


def read_strings(path):
    result = {}
    for element in ET.parse(path).getroot():
        if element.tag != 'string':
            raise ValueError('Unsupported resource type: ' + element.tag)
        key = element.attrib['name']
        if key in result:
            raise ValueError('Duplicate resource: ' + key)
        value = ''.join(element.itertext())
        value = re.sub(r'\\([nrt\\\'\"])', lambda match: ESCAPES[match[1]], value)
        result[key] = apple_format(value)
    return result


def with_fallback(base, translation):
    return {key: translation.get(key, value) for key, value in base.items()}


def quote_strings(value):
    value = value.replace('\\', '\\\\').replace('"', '\\"')
    value = value.replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    return '"' + value + '"'


def outputs(root):
    source = root / 'ui/src/commonMain/composeResources'
    base = read_strings(source / 'values/strings.xml')
    for apple_locale, compose_locale in [('zh-Hans', 'values'), ('zh-Hant', 'values-zh-rTW'), ('en', 'values-en')]:
        values = with_fallback(base, read_strings(source / compose_locale / 'strings.xml'))
        text = '// Generated by iosapp/scripts/sync_native_strings.py; edit Compose source resources.\n'
        text += '\n'.join(quote_strings(key) + ' = ' + quote_strings(value) + ';' for key, value in sorted(values.items())) + '\n'
        yield root / 'iosapp/Nodyssey/Native/Resources' / (apple_locale + '.lproj') / 'Localizable.strings', text, len(values)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    for path, text, count in outputs(root):
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit('Native strings out of sync: ' + str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(str(path.relative_to(root)) + ': ' + str(count) + ' keys')


if __name__ == '__main__':
    main()
